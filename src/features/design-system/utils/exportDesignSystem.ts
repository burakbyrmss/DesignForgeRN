import type { Answers } from '@/features/design-system/types/answers.types';
import type { Tokens } from '@/features/design-system/types/tokens.types';

export type ExportFormat = 'markdown' | 'tailwind' | 'json';

export function exportToJson(answers: Answers, tokens: Tokens): string {
  return JSON.stringify({ answers, tokens }, null, 2);
}

export function exportToMarkdown(answers: Answers, tokens: Tokens): string {
  const { color, typography, spacing, radius, motion } = tokens;

  return `# ${answers.appName} Design System

## Brand
- Tones: ${answers.brandTones.join(', ')}
- Philosophy: ${answers.designPhilosophy}

## Colors
| Token | Value |
| --- | --- |
| primary | ${color.primary} |
| primaryHover | ${color.primaryHover} |
| background | ${color.background} |
| surface | ${color.surface} |
| text | ${color.text} |
| success | ${color.success} |
| error | ${color.error} |
| warning | ${color.warning} |

## Typography
- Font: ${typography.fontFamily}
- H1: ${typography.h1.fontSize}px / ${typography.h1.lineHeight}px
- H2: ${typography.h2.fontSize}px / ${typography.h2.lineHeight}px
- Body: ${typography.body.fontSize}px / ${typography.body.lineHeight}px

## Spacing
- xs: ${spacing.xs}px
- sm: ${spacing.sm}px
- md: ${spacing.md}px
- lg: ${spacing.lg}px
- xl: ${spacing.xl}px

## Radius
- sm: ${radius.sm}px
- md: ${radius.md}px
- lg: ${radius.lg}px

## Motion
- Fast: ${motion.durationFast}ms
- Normal: ${motion.durationNormal}ms
- Slow: ${motion.durationSlow}ms

## Accessibility
- Mode: ${answers.accessibilityMode}
- Contrast ratio: ${tokens.contrastRatio}:1
- Dark mode: ${answers.darkModeEnabled ? 'enabled' : 'disabled'}
`;
}

export function exportToTailwind(answers: Answers, tokens: Tokens): string {
  const { color, typography, spacing, radius, motion } = tokens;

  return `/** ${answers.appName} — generated by DesignForge */

module.exports = {
  theme: {
    extend: {
      colors: {
        primary: '${color.primary}',
        'primary-hover': '${color.primaryHover}',
        background: '${color.background}',
        surface: '${color.surface}',
        'text-muted': '${color.textMuted}',
        success: '${color.success}',
        error: '${color.error}',
        warning: '${color.warning}',
        info: '${color.info}',
      },
      fontFamily: {
        sans: ['${typography.fontFamily}', 'system-ui', 'sans-serif'],
      },
      fontSize: {
        h1: ['${typography.h1.fontSize}px', { lineHeight: '${typography.h1.lineHeight}px' }],
        h2: ['${typography.h2.fontSize}px', { lineHeight: '${typography.h2.lineHeight}px' }],
        body: ['${typography.body.fontSize}px', { lineHeight: '${typography.body.lineHeight}px' }],
        caption: ['${typography.caption.fontSize}px', { lineHeight: '${typography.caption.lineHeight}px' }],
      },
      spacing: {
        xs: '${spacing.xs}px',
        sm: '${spacing.sm}px',
        md: '${spacing.md}px',
        lg: '${spacing.lg}px',
        xl: '${spacing.xl}px',
        xxl: '${spacing.xxl}px',
      },
      borderRadius: {
        sm: '${radius.sm}px',
        md: '${radius.md}px',
        lg: '${radius.lg}px',
        xl: '${radius.xl}px',
      },
      transitionDuration: {
        fast: '${motion.durationFast}ms',
        normal: '${motion.durationNormal}ms',
        slow: '${motion.durationSlow}ms',
      },
    },
  },
};
`;
}

export function exportDesignSystem(
  format: ExportFormat,
  answers: Answers,
  tokens: Tokens,
): string {
  switch (format) {
    case 'markdown':
      return exportToMarkdown(answers, tokens);
    case 'tailwind':
      return exportToTailwind(answers, tokens);
    case 'json':
      return exportToJson(answers, tokens);
    default: {
      const exhaustive: never = format;
      return exhaustive;
    }
  }
}
